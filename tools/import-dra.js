const fs=require('fs');
const path=require('path');
const {importDirectory}=require('./usfm.js');
function generate(directory){
  const {library,hashes}=importDirectory(directory,'dra');
  const counts=require('../data/dra-chapter-inventory.json');
  for(const [id,chapters] of Object.entries(counts)) if(library[id].chapters!==chapters) throw new Error('Chapter inventory mismatch: '+id);
  const bundle='/* Public Domain engDRA, eBible.org. Generated by tools/import-dra.js. */\nconst draLibrary = '+JSON.stringify(library)+';\n';
  return {bundle,hashes};
}
if(require.main===module){
  if(!process.argv[2]) throw new Error('Usage: node tools/import-dra.js SOURCE_DIRECTORY');
  const {bundle,hashes}=generate(path.resolve(process.argv[2]));
  fs.writeFileSync(path.join(__dirname,'../js/bible/dra.js'),bundle);
  fs.writeFileSync(path.join(__dirname,'../data/dra-source-checksums.json'),JSON.stringify(hashes,null,2)+'\n');
  console.log('Imported 73 DRA books; generated per-file SHA-256 provenance.');
}
module.exports={generate};
